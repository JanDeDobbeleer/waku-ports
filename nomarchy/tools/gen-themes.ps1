# Renders themes\<name>\shell.toml from default\themed\shell.toml.tpl and each theme's colors.toml, and
# writes themes\ThemeList.js (the names the theme picker lists). The output is committed: the shell
# reads it directly, nothing runs at start. Run this after editing the template or a theme's colors.
#   pwsh -NoProfile -File tools\gen-themes.ps1
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'theme-lib.ps1')
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$themes = Join-Path $root 'themes'
$utf8 = New-Object Text.UTF8Encoding $false
$template = [IO.File]::ReadAllText((Join-Path $root 'default\themed\shell.toml.tpl'))

$names = @()
foreach ($dir in Get-ChildItem $themes -Directory | Sort-Object Name) {
  $colorsPath = Join-Path $dir.FullName 'colors.toml'
  if (-not (Test-Path $colorsPath)) { continue }
  [IO.File]::WriteAllText((Join-Path $dir.FullName 'shell.toml'),
    (Render-ShellToml $template (Read-ThemeColors $colorsPath)), $utf8)
  $names += $dir.Name
}
$list = ($names | ForEach-Object { '  "' + $_ + '"' }) -join ",`n"
[IO.File]::WriteAllText((Join-Path $themes 'ThemeList.js'),
  ".pragma library`n`n// Generated by tools/gen-themes.ps1.`nvar names = [`n$list`n]`n", $utf8)
Write-Host "$($names.Count) themes"
